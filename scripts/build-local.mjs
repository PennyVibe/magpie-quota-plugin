import { build } from 'esbuild';
import { isBuiltin } from 'node:module';
import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compatibleRuntime, runtimeRequirement } from '../local/runtime-support.cjs';

const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
const uiOnly = process.argv.includes('--ui-only');
if (!compatibleRuntime(uiOnly ? 'darwin' : process.platform, process.versions)) throw Error(runtimeRequirement(uiOnly ? 'darwin' : process.platform));
if (!uiOnly && !((process.platform === 'darwin' && ['arm64', 'x64'].includes(process.arch)) || (process.platform === 'win32' && process.arch === 'x64'))) {
  throw Error('完整构建需要 macOS arm64/x64 或 Windows x64；其他系统可使用 --ui-only。');
}
await mkdir('generated', { recursive: true });
const inline = source => source.replaceAll('</script', '<\\/script');
const connect = await build({ entryPoints: ['local/connect-client.ts'], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2022', minify: true, charset: 'utf8', metafile: true, loader: { '.svg': 'text' }, define: { 'process.env.NODE_ENV': '"production"' } });
const connectJs = inline(connect.outputFiles[0].text);
const connectCss = await readFile('local/connect-style.css', 'utf8');
const connectHtml = `<!doctype html><html lang="zh-CN"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Magpie 安全连接</title><style>${connectCss}</style></head><body><main id="app"></main><script>${connectJs}</script></body></html>`;
await writeFile('generated/local-connect.ts', `// Generated by npm run local:build.\nexport const localConnectHtml = ${JSON.stringify(connectHtml)};\n`);
const widget = await build({ entryPoints: ['widget/main.ts'], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2022', minify: true, charset: 'utf8', metafile: true, loader: { '.svg': 'text' } });
const css = await readFile('widget/style.css', 'utf8');
const widgetHtml = `<!doctype html><html lang="zh-CN"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Magpie 额度看板</title><style>${css}</style></head><body><main id="app"></main><script>${inline(widget.outputFiles[0].text)}</script></body></html>`;
await writeFile('generated/local-widget.ts', `// Generated by npm run local:build.\nexport const localWidgetHtml = ${JSON.stringify(widgetHtml)};\n`);
if (!uiOnly) {
  // 每次只保留当前平台的产物，避免跨平台打包时混入旧 helper。
  await rm('dist/local', { recursive: true, force: true });
  await mkdir('dist/local', { recursive: true });
  const result = await build({ entryPoints: ['local/main.ts'], outfile: 'dist/local/server.mjs', bundle: true, platform: 'node', format: 'esm', target: 'node22', minify: false, sourcemap: false, metafile: true, loader: { '.svg': 'text' }, banner: { js: "#!/usr/bin/env node\nimport { createRequire as __createRequire } from 'node:module';const require = __createRequire(import.meta.url);" } });
  const external = Object.values(result.metafile.outputs).flatMap(output => output.imports).filter(item => item.external && !isBuiltin(item.path));
  if (external.length) throw Error(`Local bundle contains runtime dependencies: ${external.map(item => item.path).join(', ')}`);
  const packageDirectories = new Set();
  for (const graph of [connect.metafile, widget.metafile, result.metafile]) {
    for (const input of Object.keys(graph.inputs)) {
      const absolute = path.resolve(root, input).replaceAll('\\', '/'), marker = absolute.lastIndexOf('/node_modules/');
      if (marker < 0) continue;
      const segments = absolute.slice(marker + '/node_modules/'.length).split('/');
      const packageName = segments[0].startsWith('@') ? segments.slice(0, 2).join('/') : segments[0];
      packageDirectories.add(absolute.slice(0, marker + '/node_modules/'.length) + packageName);
    }
  }
  const notices = [];
  for (const directory of [...packageDirectories].sort()) {
    const info = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
    notices.push(`${info.name}@${info.version} (${info.license ?? 'See license below'})`);
    for (const file of await readdir(directory)) if (/^(license|copying|notice)(\.|$)/i.test(file)) notices.push(await readFile(path.join(directory, file), 'utf8'));
  }
  const platformRuntime = process.platform === 'darwin' ? { macOS: '>=13.0' } : { windows: '>=11', libuv: '>=1.51.0' };
  await writeFile('dist/local/THIRD_PARTY_NOTICES.txt', notices.join('\n\n') + '\n');
  const packageInfo = JSON.parse(await readFile('package.json', 'utf8'));
  await writeFile('dist/local/launch.cjs', await readFile('local/launch.cjs', 'utf8'));
  await writeFile('dist/local/runtime-support.cjs', await readFile('local/runtime-support.cjs', 'utf8'));
  await writeFile('dist/local/runtime.json', JSON.stringify({ name: 'magpie-quota-local', version: packageInfo.version, node: '>=22.13.0', platform: process.platform, arch: process.arch, ...platformRuntime, nativeHelper: null, credentialStorage: 'plaintext JSON' }, null, 2) + '\n');
}
console.log(`Local UI generated: connect ${Buffer.byteLength(connectHtml)} bytes; widget ${Buffer.byteLength(widgetHtml)} bytes${uiOnly ? '' : `; standalone ${process.platform} STDIO runtime built`}.`);
